#!/usr/bin/env python3
"""Write the kernel listening-socket macros from the census JSON.

The counts are the kernel's (netstat on W, ss on L). The server's own
listening lines are not read. Each file's binary sha256 must be the one
in lab/gates/measured-W.json or measured-L.json.

    python paper/census_macros.py
    python paper/census_macros.py --check
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
W_JSON = ROOT / "results" / "census-w.json"
L_JSON = ROOT / "results" / "census-l.json"
MACROS = ROOT / "results" / "census-macros.tex"
TABLE = ROOT / "results" / "tables" / "census.tex"

# (host, backend, mode, listener, workers) -> macro name, table layout words
ROWS = (
    ("W", "IOCP", "one-port", "shared", 1, "CensusWIocpOnePort", "one-port, shared listener, one worker"),
    ("W", "IOCP", "dedicated", "shared", 1, "CensusWIocpDedicated", "dedicated, one socket per protocol"),
    ("L", "epoll", "one-port", "shared", 1, "CensusLEpollOnePort", "one-port, shared listener, one worker"),
    ("L", "epoll", "dedicated", "shared", 1, "CensusLEpollDedicated", "dedicated, one socket per protocol"),
    ("L", "epoll", "one-port", "reuseport", 2, "CensusLEpollReuseport", "one-port, SO\\_REUSEPORT, two workers"),
    ("L", "io_uring", "one-port", "shared", 1, "CensusLIouringOnePort", "one-port, shared listener, one worker"),
    ("L", "io_uring", "dedicated", "shared", 1, "CensusLIouringDedicated", "dedicated, one socket per protocol"),
)


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def spell_date(iso: str) -> str:
    year, month, day = iso.split("-")
    names = ("January", "February", "March", "April", "May", "June", "July", "August",
             "September", "October", "November", "December")
    return f"{int(day)} {names[int(month) - 1]} {year}"


def index_runs(doc: dict) -> dict:
    out = {}
    for run in doc["runs"]:
        if not run.get("agree"):
            raise SystemExit(f"{doc['host']} {run['mode']} {run['backend']}: the kernel readings disagree")
        if run.get("kernel_listen_count") != len(run.get("netstat", run.get("ss", []))):
            raise SystemExit(f"{doc['host']} {run['mode']}: count does not match the kernel rows")
        key = (doc["host"], run["backend"], run["mode"], run["listener"], run["workers"])
        out[key] = run["kernel_listen_count"]
    return out


def check_gate(doc: dict, gate: dict) -> None:
    want = gate["binaries"]["oneport"]
    if doc["binary_sha256"] != want:
        raise SystemExit(f"{doc['host']} binary {doc['binary_sha256']} is not the gate's {want}")
    if doc.get("load") is not False:
        raise SystemExit(f"{doc['host']}: the census record does not say that no load was sent")


def render(w_doc: dict, l_doc: dict, w_gate: dict, l_gate: dict) -> tuple[str, str]:
    check_gate(w_doc, w_gate)
    check_gate(l_doc, l_gate)
    counts = {}
    counts.update(index_runs(w_doc))
    counts.update(index_runs(l_doc))
    if spell_date(w_doc["date"]) != spell_date(l_doc["date"]):
        raise SystemExit("the two census files name different dates")
    lines = [
        "% Generated by paper/census_macros.py from results/census-w.json and results/census-l.json.",
        "% The counts are the kernel's. Do not edit.",
        f"\\newcommand{{\\CensusDate}}{{{spell_date(w_doc['date'])}}}",
    ]
    body = ["% Generated by paper/census_macros.py. Do not edit."]
    backend = {"io_uring": "io\\_uring"}
    for host, back, mode, listener, workers, name, layout in ROWS:
        key = (host, back, mode, listener, workers)
        if key not in counts:
            raise SystemExit(f"missing census row {key}")
        lines.append(f"\\newcommand{{\\{name}}}{{{counts[key]}}}")
        body.append(f"{host} & {backend.get(back, back)} & {layout} & \\{name} \\\\")
    return "\n".join(lines) + "\n", "\n".join(body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    w_doc, l_doc = load(W_JSON), load(L_JSON)
    w_gate = load(ROOT / "lab" / "gates" / "measured-W.json")
    l_gate = load(ROOT / "lab" / "gates" / "measured-L.json")
    macros, table = render(w_doc, l_doc, w_gate, l_gate)
    if args.check:
        if MACROS.read_text(encoding="utf-8") != macros or TABLE.read_text(encoding="utf-8") != table:
            raise SystemExit("census macros are not what paper/census_macros.py writes")
        return 0
    MACROS.write_text(macros, encoding="utf-8")
    TABLE.parent.mkdir(exist_ok=True)
    TABLE.write_text(table, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
