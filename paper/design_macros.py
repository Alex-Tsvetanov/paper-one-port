# ---------------------------------------------------------------- reading


def normalised(path: Path) -> str:
    return " ".join(path.read_text(encoding="utf-8").split())


class SourceError(RuntimeError):
    pass


def match_once(text: str, pattern: str, where: str) -> re.Match:
    found = list(re.finditer(pattern, text))
    if len(found) != 1:
        raise SourceError(f"{where}: pattern {pattern!r} matches {len(found)} times, not once")
    return found[0]


def read_specs(specs: list[Spec] = SPECS) -> list[tuple[str, str, str]]:
    """(name, value, note) for every macro, in table order."""
    texts: dict[Path, str] = {}
    out: list[tuple[str, str, str]] = []
    for spec in specs:
        text = texts.setdefault(spec.source, normalised(spec.source))
        m = match_once(text, spec.pattern, spec.source.name)
        groups = m.groups()
        if len(groups) != len(spec.names):
            raise SourceError(f"{spec.names}: {len(groups)} groups for {len(spec.names)} names")
        for name, raw in zip(spec.names, groups):
            note = spec.source.relative_to(ROOT).as_posix() + (f", {spec.note}" if spec.note else "")
            out.append((name, spec.fmt(raw.strip().rstrip(",")), note))
    return out


def values_of(items: list[tuple[str, str, str]]) -> dict[str, str]:
    return {n: v for n, v, _ in items}


def plain(v: str) -> str:
    return v.replace("{,}", "")


def pin_disagreements(values: dict[str, str]) -> list[str]:
    text = normalised(PINS)
    out = []
    for name, pattern in PIN_CROSS:
        pinned = match_once(text, pattern, PINS.name).group(1)
        if pinned != values[name]:
            out.append(f"{name}: hypotheses.md says {values[name]}, pins.cmake says {pinned}")
    return out


def code_disagreements(values: dict[str, str]) -> list[str]:
    out = []
    for name, rel, pattern, conv in CODE_CROSS:
        code = conv(match_once(normalised(ROOT / rel), pattern, rel).group(1))
        if code != plain(values[name]):
            out.append(f"{name}: hypotheses.md says {plain(values[name])}, {rel} holds {code}")
    return out


# ---------------------------------------------------------------- writing


DASHES = "\u2010\u2011\u2012\u2013\u2014\u2015\u2212\ufe58\ufe63\uff0d"


def render(items: list[tuple[str, str, str]]) -> str:
    seen: set[str] = set()
    lines = [HEAD]
    for name, value, note in items:
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"macro name {name!r} is not letters only")
        if name in seen:
            raise ValueError(f"macro {name} defined twice")
        if any(c in value for c in DASHES) or "--" in value:
            raise ValueError(f"macro {name}'s value {value!r} holds a dash")
        seen.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}  % {note}\n")
    return "".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "design-macros.tex")
    ap.add_argument("--check-code", action="store_true", help="print where the code's constants differ from the frozen values")
    a = ap.parse_args(argv)
    items = read_specs()
    values = values_of(items)
    pins = pin_disagreements(values)
    if pins:
        for p in pins:
            print("pins disagree:", p, file=sys.stderr)
        return 1
    if a.check_code:
        diffs = code_disagreements(values)
        for d in diffs:
            print("code differs:", d)
        print(f"check-code: {len(CODE_CROSS)} constants compared, {len(diffs)} differ")
    text = render(items)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"design macros: {len(items)} to {a.out}")
