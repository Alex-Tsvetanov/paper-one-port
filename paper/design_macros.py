#!/usr/bin/env python3
"""The paper's design macros (results/design-macros.tex), read from the frozen and pinned files.

    python paper/design_macros.py [--out results/design-macros.tex] [--check-code]

The method half of the paper states the design: its constants, its rules and the versions it
pins. Every number it states comes from a macro (Papers CLAUDE.md: "Numbers in papers come only
from generated results/macros.tex"; hypotheses.md section 13). The results come from
analysis/macros.py; the design constants come from here. Nothing is typed in by hand: each macro
names its source file and a pattern that must match that file exactly once, so a value that is
not in its source, or is there twice, stops the run.

The sources:
  - hypotheses.md: the frozen text and its revision log, the only source of a design value;
  - bench/cmake/pins.cmake: the pinned versions of the libraries and competitors;
  - design/status.md and design/w-procedure.md: the hosts' processors and Windows' timer tick,
    as read on the hosts (records of a reading, not design values).

The generator lives in paper/, not in analysis/: the revision log records that no file of
analysis/ changed after ANALYSIS_COMMIT (entry "ANALYSIS_COMMIT, before the code freeze",
item 3), and the pilot names that commit again. A paper-only script there would break that
statement.

--check-code compares the frozen values with the constants the code holds for them and prints
each disagreement. It never changes an emitted value: the paper states the frozen text.

Names are letters only, as in analysis/macros.py, and none of them is a name analysis/macros.py
emits (paper/test_design_macros.py checks it), so both files can be loaded together.
"""

