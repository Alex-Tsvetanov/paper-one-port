# ---------------------------------------------------------------- formatting


def grouped(s: str) -> str:
    """Thousands grouped by a thin comma, as analysis/macros.py groups them."""
    s = s.replace(",", "")
    whole, _, frac = s.partition(".")
    if len(whole) > 3:
        parts = []
        while len(whole) > 3:
            parts.insert(0, whole[-3:])
            whole = whole[:-3]
        whole = "{,}".join([whole] + parts)
    return whole + ("." + frac if frac else "")


def verbatim(s: str) -> str:
    return s


def iso_date(s: str) -> str:
    d = dt.date.fromisoformat(s)
    return f"{d.day} {d.strftime('%B')} {d.year}"


def power_of_two(s: str) -> str:
    return grouped(str(2 ** int(s)))


def listing(values: list[str]) -> str:
    """1, 2 and 3."""
    return ", ".join(values[:-1]) + " and " + values[-1]


