def laptop_specs() -> list[D.Spec]:
    kept = []
    for s in D.SPECS:
        if set(s.names) & DROPPED:
            if s.names == ("SizingCommit",):
                kept.append(D.Spec(("SizingCommitL",), s.source, s.pattern, s.fmt, s.note + "; L's R_C"))
            elif not set(s.names) <= DROPPED:
                raise ValueError(f"a spec mixes kept and dropped names: {s.names}")
            continue
        kept.append(s)
    return kept + LAPTOP_SPECS


def w_read_items(archive: Path) -> list[tuple[str, str, str]]:
    sums = Path(str(archive) + ".sha256").read_text(encoding="utf-8").split()
    if not sums or sums[0] != C.sha256_file(archive):
        raise ValueError(f"{archive.name}: its sha256 does not equal its .sha256 file's")
    with tarfile.open(archive, "r:gz") as tf:
        names = [m for m in tf.getmembers() if m.isfile() and m.name.replace("\\", "/").endswith("out/w-read.json")]
        if len(names) != 1:
            raise ValueError(f"{archive.name}: {len(names)} files out/w-read.json, not one")
        rec = json.loads(tf.extractfile(names[0]).read().decode("utf-8-sig"))
    if rec.get("job") != "w-read-1":
        raise ValueError(f"{archive.name}: the record of job {rec.get('job')!r}, not w-read-1")
    os_ = rec["os"]
    if not re.fullmatch(r"\d+\.\d+", str(os_["os_build"])) or int(os_["current_build"]) < 22000:
        raise ValueError(f"{archive.name}: not a Windows 11 build: {os_['os_build']}")
    note = f"lab job a0 (w-read-1), {archive.name} sha256 {sums[0][:8]}"
    return [("HostWBuild", str(os_["os_build"]), f"{note}: OS build"),
            ("HostWVersion", str(os_["display_version"]), f"{note}: Windows' display version"),
            ("HostFirmware", str(os_["firmware"]), f"{note}: the laptop's firmware")]


def build(archive: Path) -> str:
    items = D.read_specs(laptop_specs())
    items += w_read_items(archive)
    values = D.values_of(items)
    problems = D.pin_disagreements(values)
    if not (values["AnalysisRunCommit"] == values["AnalysisCommit"] == values["SizingCommit"]):
        problems.append("the laptop's analysis did not run from ANALYSIS_COMMIT, or W's R was sized at another commit")
    if values["HostWCpu"] != values["HostLCpu"]:
        problems.append(f"W's processor {values['HostWCpu']} is not L's {values['HostLCpu']}")
    if problems:
        raise ValueError("sources disagree: " + "; ".join(problems))
    others = set()
    for f in ("macros.tex", "hardcase-macros.tex", "w-evidence-macros.tex", "b2-macros.tex", "ops-macros.tex"):
        if (C.LW / f).exists():
            others |= C.macro_names(C.LW / f)
    others |= C.macro_names(C.RESULTS / "trace-macros.tex")
    clash = {n for n, _, _ in items} & others
    if clash:
        raise ValueError(f"names another file of the laptop set holds: {sorted(clash)}")
    text = D.render(items)
    return text.replace(D.HEAD, HEAD, 1)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--w-read-archive", type=Path, required=True, help="lab job a0's archive, w-read-1.tar.gz")
    ap.add_argument("--check", action="store_true", help="compare with the committed file, write nothing")
    a = ap.parse_args(argv)
    text = build(a.w_read_archive)
    rc = C.write_all({OUT: text}, a.check)
    if not a.check:
        print(f"design macros (laptop): {text.count(chr(10)) - 4} to {OUT.relative_to(C.ROOT).as_posix()}")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
