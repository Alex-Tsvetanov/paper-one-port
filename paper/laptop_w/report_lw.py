#!/usr/bin/env python3
"""The paper's counts and tables of the laptop's analysis (results/laptop-w/report-macros.tex, tables/*.tex).

    python paper/laptop_w/report_lw.py [--check]

paper/report_macros.py, applied to the laptop's results files: results/laptop-w/decisions.csv,
summary.json, not-run.json and provenance.json, and the laptop set's macro files. It writes the same
counts over the outputs (per hypothesis the cells in Holm, those that pass, the losses, the cells
untested, not run or short of R) and the same tables, with three differences:
  - the four macros that October's results/macros-provenance.json gave (the lines its TeX escaping
    changed, and the L-against-W reruns of the analysis) are not written: they describe October's
    analysis, whose W rows were the desktop's. In their place the laptop's provenance gives how many
    times the analysis ran and whether its outputs were byte-identical;
  - the tables print paper wording: "Linux" and "Windows", the comparison in words, and a cell in
    words; the verdict of the two cost cells outside the family is worded from their frozen
    treatment (the new pilot entry, item 7), not from the desktop's reason the analysis's text
    names (the review's LOW, status.md, "The frozen analysis on the laptop's W rows", section 5);
  - CostClaimsWords lists the claims of "no measurable cost" with "Linux" and "Windows", since the
    analysis's CostClaims prints L and W.
Every verdict is the analysis's text, cut before its first parenthesis, except where a fixed map
words it; a reason is the runner's text under report_macros.py's fixed labels. An unknown key, a
macro name no file of the laptop set holds, or a count on which two results files disagree stops
the run. A printed host, family or cell label in any table stops it too.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lw_common as C  # noqa: E402
import report_macros as RM  # noqa: E402  paper/report_macros.py, read only
import cells as AC  # noqa: E402  analysis/cells.py, read only

AM = C.AM
DECISIONS = C.LW / "decisions.csv"
SUMMARY = C.LW / "summary.json"
NOT_RUN = C.LW / "not-run.json"
PROVENANCE = C.LW / "provenance.json"
MACROS = C.LW / "macros.tex"
HARDCASE = C.LW / "hardcase-macros.tex"
OTHER_SET = ("design-macros.tex", "w-evidence-macros.tex", "b2-macros.tex", "ops-macros.tex")
TRACE = C.RESULTS / "trace-macros.tex"   # October's, L alone (lab job st1)
OUT = C.LW / "report-macros.tex"

HEAD = ("% Generated by paper/laptop_w/report_lw.py from results/laptop-w/decisions.csv, summary.json,\n"
        "% not-run.json and provenance.json. Do not edit. It decides nothing. No desktop row is read.\n")
TABLE_HEAD = "% Generated by paper/laptop_w/report_lw.py. Do not edit.\n"

# Verdict heads that print an internal label or the desktop's reason, and the words a table prints.
VERDICT_WORDS = {
    "outside the confirmatory cost family: generator-bound on W": "outside the family: run in the pilot only",
}
ARM = {"one-port": "one-port", "dedicated": "dedicated", "server": "server", "competitor": "competitor",
       "proxy": "proxy", "replay": "replay", "peek": "peek", "inproc": "in-process", "relay": "relay"}
ROLE = {"one-port": "one-port", "dedicated": "dedicated", "reuseport": "group", "shared": "shared",
        "server": "server", "proxy": "proxy", "variant": "form", "default": "default", "other": "other",
        "inproc": "in-process", "relay": "relay"}
METRIC = {"conn_per_s": "conn./s", "req_per_s": "req./s", "ttfb_median_us": "median TTFB", "W": "footprint",
          "cpu": "CPU per conn.", None: "conn./s"}


# report_macros.py's reason labels that print the footprint's symbol W, which reads as a host label.
REASON_WORDS = {"W moved beyond its settling bound": "the counted footprint moved beyond its settling bound"}


def reason_label(reason: str) -> str:
    lab = RM.label(reason)
    return REASON_WORDS.get(lab, lab)


def verdict(v: str) -> str:
    head = RM.verdict_head(v)
    return VERDICT_WORDS.get(head, head)


# ---------------------------------------------------------------- counts


def counts(dec: list[dict], summary: dict, not_run: dict, prov: dict) -> AM.Macros:
    mc = AM.Macros()
    fams = summary["families"]
    truth = RM.truth
    mc.add("CountDecisionRows", AM.count(len(dec)), "rows of results/laptop-w/decisions.csv")
    for hyp, w in RM.HYP_WORDS.items():
        rows = [r for r in dec if r["hyp"] == hyp]
        holm = [r for r in rows if truth(r["holm"])]
        mc.add(f"CountCells{w}", AM.count(len(rows)), f"{hyp}: cells")
        mc.add(f"CountHolm{w}", AM.count(len(holm)), f"{hyp}: cells in Holm")
        mc.add(f"CountPass{w}", AM.count(sum(truth(r["passes"]) for r in holm)), f"{hyp}: cells that pass")
        mc.add(f"CountFail{w}", AM.count(sum(not truth(r["passes"]) for r in holm)), f"{hyp}: cells in Holm that do not pass")
    for fam, hyps in (("C", ("C1", "C2", "C3")), ("B3", ("B3",)), ("M", ("M1", "M2", "M3"))):
        holm = [r for r in dec if r["hyp"] in hyps and truth(r["holm"])]
        if len(holm) != fams[fam]["m"] or sum(truth(r["passes"]) for r in holm) != fams[fam]["passed"]:
            raise ValueError(f"decisions.csv and summary.json disagree on family {fam}")
    cost = [r for r in dec if r["family"] == "C"]
    mc.add("CountCostOutside", AM.count(sum(r["verdict"].startswith("outside the confirmatory cost family") for r in cost)),
           "cost cells outside the family by their frozen treatment")
    mc.add("CountCostUnresolved", AM.count(sum(r["verdict"].startswith("not resolved") for r in cost)),
           "cost cells the pilot did not resolve")
    mc.add("CountCostMeasured", AM.count(sum("a measured cost" in r["verdict"] for r in cost)),
           "cost cells whose interval lies wholly outside the margin")
    for host in ("L", "W"):
        hc = [r for r in cost if r["cell"].split(".")[1] == host]
        mc.add(f"CountCostHolm{host}", AM.count(sum(truth(r["holm"]) for r in hc)), f"cost cells in Holm on {host}")
        mc.add(f"CountCostPass{host}", AM.count(sum(truth(r["holm"]) and truth(r["passes"]) for r in hc)),
               f"cost cells that pass on {host}")
    b3 = [r for r in dec if r["family"] == "B3"]
    mc.add("CountLossBThree", AM.count(sum("loss" in r["verdict"] for r in b3)), "B3 cells with a loss")
    desc = [r for r in b3 if not truth(r["holm"])]
    mc.add("CountDescBThree", AM.count(len(desc)), "B3's descriptive cells")
    mc.add("CountDescShortBThree", AM.count(sum(int(r["valid_sessions"]) < int(r["R"]) for r in desc)),
           "B3's descriptive cells short of R")
    m = [r for r in dec if r["family"] == "M"]
    mc.add("CountUntestedM", AM.count(sum(not truth(r["tested"]) for r in m)), "M cells untested (no valid session)")
    statuses = Counter(c["status"] for c in not_run["cells"])
    if sum(statuses[k] for k in ("not run", "ran, short of R")) != len(not_run["cells"]):
        raise ValueError("not-run.json: a status this file does not know")
    mc.add("CountNotRunList", AM.count(len(not_run["cells"])), "cells results/laptop-w/not-run.json lists")
    mc.add("CountNotRunNotRun", AM.count(statuses["not run"]), "of them, not run")
    mc.add("CountNotRunShort", AM.count(statuses["ran, short of R"]), "of them, ran and short of R")
    sec = [c for c in not_run["cells"] if c["cell"].startswith("S.")]
    mc.add("CountSecShortNone", AM.count(sum(c["status"] == "ran, short of R" and c["valid_sessions"] == 0 for c in sec)),
           "section 10 cells that ran and have no valid session")
    mc.add("CountSecNotRun", AM.count(sum(c["status"] == "not run" for c in sec)), "section 10 cells not run")
    mc.add("CountSecSslh", AM.count(sum("sslh-ev" in c["cell"] for c in sec)), "section 10 cells of sslh-ev short of R")
    by_id = {c["cell"]: c for c in not_run["cells"]}
    mixed = by_id["S.mixed.C1.L.io_uring"]
    reasons = mixed["rows"]["invalid_reasons_numbers_as_N"]
    mc.add("CountMixedIouringSessions", AM.count(mixed["rows"]["sessions"]), "the mixed cell on io_uring: sessions run")
    mc.add("CountMixedIouringWindows", AM.count(mixed["rows"]["windows"]), "windows")
    mc.add("CountMixedIouringValid", AM.count(mixed["rows"]["valid_windows"]), "valid windows")
    mc.add("CountMixedIouringProbe", AM.count(reasons["probe failed: http1: failed (timeout)"]), "windows whose probe timed out")
    mc.add("CountMixedIouringErrors", AM.count(reasons["errors N% > N%"]), "windows with the error share above its bound")
    ssh = [c for c in sec if c["cell"].startswith("S.ssh.C2.")]
    if len({c["rows"]["windows"] for c in ssh}) != 1 or any(c["rows"]["valid_windows"] for c in ssh):
        raise ValueError("the SSH C2 cells differ in their windows")
    mc.add("CountSshCtwoCells", AM.count(len(ssh)), "section 10's SSH C2 cells")
    mc.add("CountSshCtwoWindows", AM.count(ssh[0]["rows"]["windows"]), "windows of each, none valid")
    by_job = [e for e in summary["secondary"] if e["bullet"] == "by-job"]
    mc.add("CountByJobCells", AM.count(len(by_job)), "family cells of the analysis clustered by lab job")
    mc.add("CountByJobIntervals", AM.count(sum(e.get("interval") is not None for e in by_job)),
           "of them, with an interval (a cell needs at least 2 lab jobs)")
    if not prov.get("runs_identical") or not prov.get("hardcase_runs_identical"):
        raise ValueError("provenance.json: the analysis's runs are not byte-identical")
    mc.add("CountAnalysisRuns", AM.count(len(prov["runs"])), "runs of the frozen analysis, outputs byte-identical")
    mc.add("CountAnalysisRowsBound", AM.count(sum(int(r["rows"]) for r in prov["rows"] if r.get("role", "analysis") == "analysis")),
           "rows the analysis read, each bound to its gate")
    mc.add("CostClaimsWords", claims_words(summary), "CostClaims with Linux and Windows for L and W")
    return mc


def claims_words(summary: dict) -> str:
    items = [f"{C.need(C.PROTO, c['proto'], 'protocol')} on {C.need(C.BACKEND, c['backend'], 'backend')} "
             f"({C.need(C.HOST, c['host'], 'host')})" for c in summary["claims"]["C"]]
    if not items:
        return "none"
    return ", ".join(items[:-1]) + (" and " if len(items) > 1 else "") + items[-1]


# ---------------------------------------------------------------- tables


def cost_table(dec: list[dict], names: set[str]) -> str:
    rows = []
    for r in (r for r in dec if r["family"] == "C"):
        w = AM.word(r["cell"])
        comp, wh, proto = C.family_cell_columns(r["cell"])
        rows.append(f"{comp} & {wh} & {proto} & {RM.require(w + 'Valid', names)} & {RM.value(w + 'Median', names)} & "
                    f"{RM.interval(w, names)} & {RM.interval(w, names, 'HolmLow', 'HolmHigh')} & {verdict(r['verdict'])} \\\\")
    return TABLE_HEAD + "\n".join(rows) + "\n"


def mech_table(dec: list[dict], names: set[str]) -> str:
    rows = []
    for r in (r for r in dec if r["family"] == "M"):
        p = r["cell"].split(".")
        what = f"{C.need(C.BACKEND, p[2], 'backend')}, {C.need(C.PROTO, p[3], 'protocol')}" + (
            f", {C.need(C.SYSTEM, p[4], 'system')}" if len(p) > 4 else "")
        w = AM.word(r["cell"])
        rows.append(f"{C.COMPARISON[p[0]]} & {C.need(C.HOST, p[1], 'host')} & {what} & {RM.require(w + 'Valid', names)} & "
                    f"{RM.value(w + 'Median', names)} & {RM.interval(w, names)} & {verdict(r['verdict'])} \\\\")
    return TABLE_HEAD + "\n".join(rows) + "\n"


def invalid_table(summary: dict) -> str:
    rows = []
    for fam in ("C", "B3", "M"):
        for x in summary["families"][fam]["cells"]:
            for arm, ws in sorted(x["invalid_windows"].items()):
                labels = Counter(lab for w in ws for lab in {reason_label(reason) for reason in w["reasons"]})
                text = "; ".join(f"{k} ({v})" for k, v in sorted(labels.items(), key=lambda kv: (-kv[1], kv[0])))
                rows.append(f"{C.cell_phrase(x['cell'])} & {C.need(ARM, arm, 'arm')} & {len(ws)} & {text} \\\\")
    return TABLE_HEAD + "\n".join(rows) + "\n"


def secondary_rows() -> list[tuple[str, str, str, str, str, str]]:
    """report_macros.secondary_rows in paper wording: (bullet, cell id, metric, what, where, ratio)."""
    sec = {c.id: c for c in AC.secondary_cells()}
    fam = AC.all_family_cells()
    out = []
    for d in AC.secondary_draws():
        if d.bullet in ("wl4", "by-job"):
            continue
        if d.source in sec:
            c = sec[d.source]
            p = c.id.split(".")
            if c.bullet == "ssh":
                what, metric = f"SSH, {C.need(C.COMPARISON, p[2], 'comparison')}", AC.HYP_METRIC[p[2]]
            elif c.bullet == "mixed":
                what, metric = "mixed protocols, churn", c.metric
            elif c.bullet in ("tls-variants", "two-cores", "iocp-forms"):
                what, metric = C.need(C.VARIANT, p[-1], "variant"), c.metric
            elif c.bullet == "relay-io_uring":
                what, metric = f"relay, {C.need(C.PROTO, p[4], 'protocol')}, {C.need(C.SYSTEM, p[5], 'system')}", c.metric
            elif c.bullet == "m-ttfb-cpu":
                m = fam[c.key[0]]
                what = f"{C.COMPARISON[m.hyp]}, TTFB, {C.need(C.PROTO, m.proto, 'protocol')}" + (
                    f", {C.need(C.SYSTEM, m.system, 'system')}" if m.system else "")
                metric = c.metric
            elif c.bullet == "b3-other-mode":
                what, metric = f"footprint, other detection mode, {C.need(C.CASE, p[3], 'case')}", c.metric
            else:
                raise ValueError(f"no row text for bullet {c.bullet}")
            num, den, host, backend = c.num, c.den, c.host, c.backend
        else:
            m = fam[d.source]
            what = f"{C.COMPARISON[m.hyp]}, CPU, {C.need(C.PROTO, m.proto, 'protocol')}" + (
                f", {C.need(C.SYSTEM, m.system, 'system')}" if m.system else "")
            num, den, host, backend, metric = m.num, m.den, m.host, m.backend, "cpu"
        ratio = f"{C.need(ROLE, num, 'role')} / {C.need(ROLE, den, 'role')}, {C.need(METRIC, metric, 'metric')}"
        out.append((d.bullet, d.source, d.metric, what, C.where(host, backend), ratio))
    return out


def secondary_tables(summary: dict, not_run: dict, names: set[str]) -> tuple[str, str]:
    entries = {(e["bullet"], e["cell"], e["metric"]): e for e in summary["secondary"]}
    nr = {c["cell"]: c for c in not_run["cells"]}
    rows: list[tuple[str, str]] = []
    for bullet, cell, metric, what, wh, ratio in secondary_rows():
        e = entries[(bullet, cell, metric)]
        w = "Sec" + AM.word(bullet) + AM.word(cell) + AM.word(metric)
        if e.get("interval") is not None:
            shown = f"{RM.require(w + 'Median', names)} & [{RM.require(w + 'Low', names)}, {RM.require(w + 'High', names)}]"
        else:
            c = nr.get(cell)
            if c is None:
                raise ValueError(f"{cell}: no interval and not in not-run.json")
            shown = "\\multicolumn{2}{l}{" + ("not run" if c["status"] == "not run" else "no valid session") + "}"
        rows.append((bullet, f"{what} & {wh} & {ratio} & {e['valid_sessions']} & {shown} \\\\"))
    if len(rows) != sum(1 for e in summary["secondary"] if e["bullet"] not in ("wl4", "by-job")):
        raise ValueError("section 10's table and summary.json differ in their cells")
    first = [r for b, r in rows if b not in RM.MECH_BULLETS]
    second = [r for b, r in rows if b in RM.MECH_BULLETS]
    return TABLE_HEAD + "\n".join(first) + "\n", TABLE_HEAD + "\n".join(second) + "\n"


def wl4_table(summary: dict, names: set[str]) -> str:
    rows, cells = [], []
    for e in summary["secondary"]:
        if e["bullet"] == "wl4" and e["cell"] not in cells:
            cells.append(e["cell"])
    for cell in cells:
        vals = []
        for metric in ("cpu", "rss", "rss_peak", "ttfb_p99"):
            w = "SecWLFour" + AM.word(cell) + AM.word(metric)
            vals.append(f"\\{w}Median{{}} [\\{w}Low, \\{w}High]" if w + "Median" in names else "none")
        rows.append(" & ".join(C.family_cell_columns(cell)) + " & " + " & ".join(vals) + " \\\\")
    return TABLE_HEAD + "\n".join(rows) + "\n"


def by_job_table(summary: dict, names: set[str]) -> str:
    rows = []
    for e in summary["secondary"]:
        if e["bullet"] != "by-job" or e.get("interval") is None:
            continue
        w = "SecByJob" + AM.word(e["cell"]) + "Value"
        rows.append(" & ".join(C.family_cell_columns(e["cell"])) + f" & {RM.require(w + 'Median', names)} & "
                    f"[{RM.require(w + 'Low', names)}, {RM.require(w + 'High', names)}] & {RM.interval(AM.word(e['cell']), names)} \\\\")
    return TABLE_HEAD + "\n".join(rows) + ("\n" if rows else "")


# ---------------------------------------------------------------- main


def build() -> dict[Path, str]:
    with open(DECISIONS, encoding="utf-8", newline="") as f:
        dec = list(csv.DictReader(f))
    summary, not_run, prov = RM.read_json(SUMMARY), RM.read_json(NOT_RUN), RM.read_json(PROVENANCE)
    names = C.macro_names(MACROS)
    hc = C.macro_names(HARDCASE)
    mc = counts(dec, summary, not_run, prov)
    sec = secondary_tables(summary, not_run, names)
    others = names | hc | C.macro_names(TRACE)
    for f in OTHER_SET:
        if not (C.LW / f).exists():
            raise ValueError(f"run the generator of results/laptop-w/{f} first")
        others |= C.macro_names(C.LW / f)
    clash = set(mc.names) & others
    if clash:
        raise ValueError(f"names another macro file of the laptop set holds: {sorted(clash)}")
    out = {
        OUT: HEAD + mc.text(),
        C.TABLES / "cost.tex": cost_table(dec, names),
        C.TABLES / "b3.tex": RM.b3_table(dec, names).replace(RM.TABLE_HEAD, TABLE_HEAD, 1),
        C.TABLES / "b3-parts-competitor.tex": RM.b3_parts_table(dec, names, "Competitor").replace(RM.TABLE_HEAD, TABLE_HEAD, 1),
        C.TABLES / "b3-parts-server.tex": RM.b3_parts_table(dec, names, "Server").replace(RM.TABLE_HEAD, TABLE_HEAD, 1),
        C.TABLES / "mechanism.tex": mech_table(dec, names),
        C.TABLES / "invalid.tex": invalid_table(summary),
        C.TABLES / "secondary.tex": sec[0],
        C.TABLES / "secondary-mech.tex": sec[1],
        C.TABLES / "wl4.tex": wl4_table(summary, names),
        C.TABLES / "by-job.tex": by_job_table(summary, names),
        C.TABLES / "competitors.tex": RM.competitors_table(hc).replace(RM.TABLE_HEAD, TABLE_HEAD, 1),
    }
    for p, t in out.items():
        if p.parent == C.TABLES:
            hits = C.printed_label_hits(t)
            if hits:
                raise ValueError(f"{p.name} prints internal labels: {sorted(set(hits))[:10]}")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    a = ap.parse_args(argv)
    out = build()
    rc = C.write_all(out, a.check)
    if not a.check:
        print(f"report (laptop): {len(out)} files")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
