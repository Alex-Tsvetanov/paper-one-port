#!/usr/bin/env python3
"""B2's distributions on L's rows and the laptop's W rows (results/laptop-w/b2-macros.tex, tables/b2.tex).

    python paper/laptop_w/b2_lw.py --l HL1_HARDCASES.jsonl --w P3HARDW_HARDCASES.jsonl [--check]

paper/b2_macros.py, with the laptop's hard-case job (p3hardw) in the place of the desktop's (wh1):
per backend, the lateness of timed events and the decision latency, as distributions (count,
minimum, median, the 99th percentile at rank ceil(0.99 n), maximum), reported and not tested
(frozen section 5.2; the revision log's entry of 2026-10-08 on section 10's four outputs, item 3).
The inputs are the files results/laptop-w/hardcase-macros.tex names, checked by sha256. The L lines
must equal October's results/b2-macros.tex, since L's rows are October's; that is checked, and a
difference stops the run. It uses b2_macros.py's functions unchanged.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lw_common as C  # noqa: E402
import b2_macros as B2  # noqa: E402  paper/b2_macros.py, read only

AM = C.AM
HARDCASE = C.LW / "hardcase-macros.tex"
OUT = C.LW / "b2-macros.tex"
TABLE = C.TABLES / "b2.tex"
OCTOBER = C.RESULTS / "b2-macros.tex"
HOSTS = (("L", "hl1", ("epoll", "io_uring")), ("W", "p3hardw", ("IOCP",)))
HEAD = ("% Generated by paper/laptop_w/b2_lw.py from the hard-case rows of hl1 (L) and of the laptop's p3hardw (W),\n"
        "% named below by their sha256 (results/laptop-w/hardcase-macros.tex). Do not edit.\n"
        "% Descriptive: B2's distributions, reported and not tested. No desktop row is read.\n")
TABLE_HEAD = "% Generated by paper/laptop_w/b2_lw.py. Do not edit.\n"


def named_inputs() -> dict[str, str]:
    text = HARDCASE.read_text(encoding="utf-8")
    out = {}
    for host, job, _ in HOSTS:
        found = re.findall(rf"^% input: {host} {job} hardcases\.jsonl sha256 ([0-9a-f]{{64}})$", text, re.M)
        if len(found) != 1:
            raise ValueError(f"{HARDCASE.name} names {host}'s {job} hardcases.jsonl {len(found)} times, not once")
        out[host] = found[0]
    return out


def build(paths: dict[str, Path]) -> dict[Path, str]:
    digests = named_inputs()
    mc = AM.Macros()
    table, inputs = [], []
    counts: dict[str, tuple[int, int, int]] = {}
    for host, job, backends in HOSTS:
        rows = B2.read_rows(paths[host], digests[host], f"{host}'s {job} rows")
        C.refuse_desktop_rows(rows, f"{host}'s hard-case rows")
        inputs.append(f"% input: {host} {job} hardcases.jsonl sha256 {digests[host]}\n")
        per = B2.split(rows, host, job, backends)
        for b in backends:
            w0 = f"BTwoDist{B2.macro_word(b)}"
            mc.add(f"{w0}Runs", AM.count(len(per[b]["Runs"])), f"{host} {b}: hard-case runs")
            mc.add(f"{w0}NoWriteN", AM.count(len(per[b]["NoWrite"])),
                   f"{host} {b}: runs with no write before the end of detection, so no decision latency")
            shut, other = sorted(per[b]["Shut"]), sorted(per[b]["Other"])
            if not shut or not other:
                raise ValueError(f"{host} {b}: no run of HC21 or HC22, or no other run, that no timer ended")
            above = [cid for v, cid in other if v > shut[-1][0]]
            w = f"{w0}DecisionBytes"
            mc.add(f"{w}ShutN", AM.count(len(shut)), f"{host} {b}: runs of HC21 and HC22 among those no timer ended")
            mc.add(f"{w}ShutMin", AM.fixed(shut[0][0] / 1e3, 1), f"{host} {b}: their smallest decision latency, us")
            mc.add(f"{w}ShutMax", AM.fixed(shut[-1][0] / 1e3, 1), f"{host} {b}: their largest decision latency, us")
            mc.add(f"{w}OtherMax", AM.fixed(other[-1][0] / 1e3, 1), f"{host} {b}: the other runs' largest decision latency, us")
            mc.add(f"{w}OtherAboveN", AM.count(len(above)), f"{host} {b}: other runs above the largest of HC21 and HC22")
            mc.add(f"{w}OtherAboveCases", B2.case_list(above), f"{host} {b}: the cases of those runs")
            counts[b] = (len(per[b]["Runs"]), len(per[b]["NoWrite"]), len(shut))
            for word, unit, scale, places, label in B2.DISTS:
                values = per[b][word]
                if not values:
                    raise ValueError(f"{host} {b}: no value of {word}")
                s = B2.summary(values)
                name = f"{w0}{word}"
                mc.add(f"{name}N", AM.count(s["N"]), f"{host} {b}: {label}, runs")
                for k in B2.STATS[1:]:
                    mc.add(f"{name}{k}", AM.fixed(s[k] / scale, places), f"{host} {b}: {label}, {k}, {unit}")
                cells = " & ".join(f"\\{name}{k}" for k in B2.STATS)
                table.append(f"{C.HOST[host]}, {B2.BACKEND_TEXT[b]} & {label} ({B2.UNIT_TEX[unit]}) & {cells} \\\\")
    if counts["epoll"] != counts["io_uring"]:
        raise ValueError(f"L's two backends differ in runs, runs with no write or HC21 and HC22 runs: {counts}")
    text = HEAD + "".join(inputs) + mc.text()
    check_l_lines(text)
    return {OUT: text, TABLE: TABLE_HEAD + "\n".join(table) + "\n"}


def macro_lines(text: str, word: str) -> list[str]:
    return [ln for ln in text.splitlines() if ln.startswith(f"\\newcommand{{\\BTwoDist{word}")]


def check_l_lines(text: str) -> None:
    october = OCTOBER.read_text(encoding="utf-8")
    for word in ("Epoll", "Iouring"):
        if macro_lines(text, word) != macro_lines(october, word):
            raise ValueError(f"the L lines of {word} differ from October's {OCTOBER.name}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--l", type=Path, required=True, help="hl1's hardcases.jsonl (L)")
    ap.add_argument("--w", type=Path, required=True, help="the laptop's p3hardw hardcases.jsonl (W)")
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    a = ap.parse_args(argv)
    rc = C.write_all(build({"L": a.l, "W": a.w}), a.check)
    if not a.check:
        print("b2 (laptop): 2 files")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
