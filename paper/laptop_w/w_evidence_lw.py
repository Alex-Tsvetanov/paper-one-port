#!/usr/bin/env python3
"""Readings of the laptop's W rows that the paper owes its reader (results/laptop-w/w-evidence-macros.tex).

    python paper/laptop_w/w_evidence_lw.py --pilot-w PILOT_W.jsonl --m-w M_W.jsonl \
        --timer-rows COST_W.jsonl --timer-rows M_W.jsonl --timer-rows S_W.jsonl [--check]

paper/w_evidence_macros.py's two readings, on the laptop's rows, and one more:
1. The CPU shares of the laptop's A/A pilot in W's four C1 cells: per cell, the median over its valid
   windows of the server's busy share, the generator CPUs' busy share and the generator process's
   share. Cells 10 and 12 (churn h2c and churn MQTT) stay outside the cost family by their frozen
   treatment (the new pilot entry, item 7); these shares are reported beside that treatment, as a
   description, and decide nothing (the move's entry, item 7). The rows are named by their sha256
   in the new pilot entry, item 4.
2. How often M1's peek on IOCP switched to replay (frozen section 5.3): per M1 cell on the laptop's
   W, the switches and the connections accepted in the valid windows of each detection mode. The
   rows are named by their sha256 in results/laptop-w/summary.json's inputs.
3. Windows' timer resolution as each W window of the cost, detection-mode and secondary cells
   recorded it at its start and end (the move's entry, item 3 (d): Windows' default, recorded): the
   coarsest and current values, which must be one value each over every window of the cost, M1 and
   section 10 rows.
Nothing is decided or compared. It reuses w_evidence_macros.py's functions unchanged.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lw_common as C  # noqa: E402
import w_evidence_macros as WE  # noqa: E402  paper/w_evidence_macros.py, read only

AM = C.AM
OUT = C.LW / "w-evidence-macros.tex"
SUMMARY = C.LW / "summary.json"
HEAD = ("% Generated by paper/laptop_w/w_evidence_lw.py from the laptop's W rows: the A/A pilot (the new pilot\n"
        "% entry, item 4), M1, and the cost, M1 and section 10 rows (results/laptop-w/summary.json's inputs),\n"
        "% each checked by its sha256. Do not edit. Descriptive; no desktop row is read.\n")


def pilot_w_sha256() -> str:
    """The laptop's W pilot rows, as the new pilot entry, item 4, names them."""
    text = " ".join(C.HYP.read_text(encoding="utf-8").split())
    found = re.findall(r"The laptop's W pilot: [^;]*?; its rows, by sha256: `windows\.jsonl` ([0-9a-f]{64}) and `parts\.jsonl`",
                       text)
    if len(found) != 1:
        raise ValueError(f"hypotheses.md names the laptop's W pilot rows {len(found)} times, not once")
    return found[0]


def summary_sha256s() -> set[str]:
    return {i["sha256"] for i in json.loads(SUMMARY.read_text(encoding="utf-8"))["inputs"]}


def rows_of(path: Path, allowed: set[str], what: str) -> tuple[list[dict], str]:
    text, digest = C.read_checked(path, allowed, what)
    rows = [json.loads(ln) for ln in text.splitlines() if ln.strip()]
    C.refuse_desktop_rows(rows, what)
    if any(r.get("host") not in (None, "W") for r in rows):
        raise ValueError(f"{what}: a row of another host")
    return rows, digest


def timer_macros(mc: AM.Macros, rows: list[dict]) -> None:
    """The coarsest resolution must be one value over every window. The resolution in effect is
    reported as the value both ends of most windows read, with the count of windows where an end
    read another value, and those values; it is recorded, never set (the move's entry, item 3 (d))."""
    coarsest: set[float] = set()
    ends: list[tuple[float, float]] = []
    for r in rows:
        if r.get("cell") is None:
            continue
        pair = []
        for side in ("timer_resolution_start", "timer_resolution_end"):
            t = r.get(side)
            if not t:
                raise ValueError(f"{r.get('tag')}: no {side}")
            coarsest.add(float(t["coarsest_ms"]))
            pair.append(float(t["current_ms"]))
        ends.append((pair[0], pair[1]))
    if len(coarsest) != 1:
        raise ValueError(f"the coarsest timer resolution differs between windows: {sorted(coarsest)}")
    both = [a for a, b in ends if a == b]
    usual = max(set(both), key=both.count)
    other = [(a, b) for a, b in ends if not (a == usual and b == usual)]
    other_values = sorted({v for a, b in other for v in (a, b) if v != usual})
    mc.add("WTimerWindows", AM.count(len(ends)), "W windows of the cost, detection-mode and secondary cells whose timer resolution was read at start and end")
    mc.add("WTickMs", AM.fixed(coarsest.pop(), 3), "Windows' coarsest timer resolution, ms, in every such window")
    mc.add("WTimerCurrentMs", AM.fixed(usual, 3), "the resolution in effect at both ends of all but WTimerOtherWindows windows, ms")
    mc.add("WTimerOtherWindows", AM.count(len(other)), "windows with another resolution in effect at one end")
    if other_values:
        mc.add("WTimerOtherMs", ", ".join(AM.fixed(v, 3) for v in other_values), "that other resolution, ms")


def build(pilot_w: Path, m_w: Path, timer_rows: list[Path]) -> str:
    mc = AM.Macros()
    inputs = []
    rows, d = rows_of(pilot_w, {pilot_w_sha256()}, "the laptop's W pilot rows")
    WE.pilot_macros(mc, rows)
    inputs.append(f"% input: the laptop's W pilot windows.jsonl sha256 {d}\n")
    allowed = summary_sha256s()
    rows, d = rows_of(m_w, allowed, "the laptop's M1 rows")
    WE.switch_macros(mc, rows)
    inputs.append(f"% input: the laptop's M1 windows.jsonl sha256 {d}\n")
    if len({p.resolve() for p in timer_rows}) != len(timer_rows) or len(timer_rows) != 3:
        raise ValueError("give the laptop's cost, M1 and section 10 row files once each")
    all_rows = []
    for p in timer_rows:
        rows, d = rows_of(p, allowed, f"the laptop's rows {p.name}")
        all_rows += rows
        inputs.append(f"% input: timer resolution, windows.jsonl sha256 {d}\n")
    timer_macros(mc, all_rows)
    return HEAD + "".join(inputs) + mc.text()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--pilot-w", type=Path, required=True)
    ap.add_argument("--m-w", type=Path, required=True)
    ap.add_argument("--timer-rows", type=Path, action="append", default=[])
    ap.add_argument("--check", action="store_true", help="compare with the committed file, write nothing")
    a = ap.parse_args(argv)
    text = build(a.pilot_w, a.m_w, a.timer_rows)
    rc = C.write_all({OUT: text}, a.check)
    if not a.check:
        print(f"w evidence (laptop): {text.count(chr(10)) - 3 - 5} macros to {OUT.relative_to(C.ROOT).as_posix()}")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
