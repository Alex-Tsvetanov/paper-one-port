#!/usr/bin/env python3
"""Operations and copies per connection (WL5) on L's rows and the laptop's W rows
(results/laptop-w/ops-macros.tex, tables/ops-cost.tex, tables/ops-m1.tex).

    python paper/laptop_w/ops_lw.py --cost-l COST_L.jsonl --cost-w COST_W.jsonl --m-l M_L.jsonl --m-w M_W.jsonl [--check]

paper/ops_macros.py's parts (i) and (ii) (the revision log's entry of 2026-10-08 on section 10's
four outputs, item 4), with the laptop's cost job (p3costw) and M1 job (p3m1w) in the place of the
desktop's (wc1 and wc2, wm1): per arm, the mean over its valid windows of each window's per-connection
value (per request in keep-alive) of rule E's operations, the bytes copied in user space, received,
sent and peeked, and the wakeups during detection. No interval and no ratio. Every input is checked
against the sha256 results/laptop-w/summary.json names for it. The L lines must equal October's
results/ops-macros.tex; a difference stops the run. The tables print paper wording. It uses
ops_macros.py's functions unchanged.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lw_common as C  # noqa: E402
import ops_macros as OM  # noqa: E402  paper/ops_macros.py, read only

AM = C.AM
SUMMARY = C.LW / "summary.json"
OUT = C.LW / "ops-macros.tex"
OCTOBER = C.RESULTS / "ops-macros.tex"
HEAD = ("% Generated by paper/laptop_w/ops_lw.py from the cost family's and M1's window rows of L (pc1, ml1) and of\n"
        "% the laptop's W (p3costw, p3m1w), named below by their sha256 (results/laptop-w/summary.json's inputs).\n"
        "% Do not edit. Descriptive: WL5, the revision log's entry of 2026-10-08 on section 10's four outputs,\n"
        "% item 4 (i) and (ii). No desktop row is read.\n")
TABLE_HEAD = "% Generated by paper/laptop_w/ops_lw.py. Do not edit.\n"
FILES = (("cost_l", "pc1 cost-L"), ("cost_w", "the laptop's p3costw cost"), ("m_l", "ml1 m-L"), ("m_w", "the laptop's p3m1w M1"))


def cost_rows(cells: list[str]) -> list[str]:
    table = []
    for cell in cells:
        w = "WlFive" + AM.word(cell)
        comp, wh, proto = C.family_cell_columns(cell)
        cols = [f"\\{w}OnePortWindows/\\{w}DedicatedWindows"]
        for word in ("Ops", "Copied", "Received", "Sent"):
            cols += [f"\\{w}OnePort{word}", f"\\{w}Dedicated{word}"]
        table.append(f"{comp} & {wh} & {proto} & " + " & ".join(cols) + " \\\\")
    return table


def m1_rows(cells: list[str]) -> list[str]:
    table = []
    for cell in cells:
        w = "WlFive" + AM.word(cell)
        _, host, backend, proto = cell.split(".")
        for detect, dw in OM.M1_ARMS:
            cols = [f"\\{w}{dw}{k}" for k in ("Windows", "Ops", "Copied", "Received", "Sent", "Peeked", "Wakeups")]
            table.append(f"{C.where(host, backend)} & {C.need(C.PROTO, proto, 'protocol')} & {detect} & "
                         + " & ".join(cols) + " \\\\")
    return table


def check_l_lines(text: str) -> None:
    pat = re.compile(r"^\\newcommand\{\\WlFive(?:COne|CTwo|CThree|MOne)L")
    mine = [ln for ln in text.splitlines() if pat.match(ln)]
    october = [ln for ln in OCTOBER.read_text(encoding="utf-8").splitlines() if pat.match(ln)]
    if not mine or mine != october:
        raise ValueError(f"the L lines differ from October's {OCTOBER.name}")


def build(paths: dict[str, Path]) -> dict[Path, str]:
    allowed = {i["sha256"] for i in json.loads(SUMMARY.read_text(encoding="utf-8"))["inputs"]}
    rows: dict[str, list[dict]] = {}
    inputs = []
    for key, what in FILES:
        text, digest = C.read_checked(paths[key], allowed, what)
        rows[key] = [json.loads(ln) for ln in text.splitlines() if ln.strip()]
        C.refuse_desktop_rows(rows[key], what)
        inputs.append(f"% input: {what} windows.jsonl sha256 {digest}\n")
    mc = AM.Macros()
    cost = rows["cost_l"] + rows["cost_w"]
    OM.cost_part(mc, cost)
    m1 = [r for r in rows["m_l"] + rows["m_w"] if r.get("cell", "").startswith("M1.")]
    OM.m1_part(mc, m1)
    OM.summary_macros(mc)
    cost_cells = OM.cell_order({r["cell"] for r in cost if r.get("family") == "C" or r["cell"][:2] in ("C1", "C2", "C3")})
    m1_cells = OM.cell_order({r["cell"] for r in m1})
    text = HEAD + "".join(inputs) + mc.text()
    check_l_lines(text)
    return {OUT: text,
            C.TABLES / "ops-cost.tex": TABLE_HEAD + "\n".join(cost_rows(cost_cells)) + "\n",
            C.TABLES / "ops-m1.tex": TABLE_HEAD + "\n".join(m1_rows(m1_cells)) + "\n"}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cost-l", type=Path, required=True)
    ap.add_argument("--cost-w", type=Path, required=True)
    ap.add_argument("--m-l", type=Path, required=True)
    ap.add_argument("--m-w", type=Path, required=True)
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    a = ap.parse_args(argv)
    rc = C.write_all(build({"cost_l": a.cost_l, "cost_w": a.cost_w, "m_l": a.m_l, "m_w": a.m_w}), a.check)
    if not a.check:
        print("ops (laptop): 3 files")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
