#!/usr/bin/env python3
"""Section 10's untimed tables of lab job st1, in paper wording, for the laptop set
(results/laptop-w/tables/counter-check.tex, syscalls.tex, ops-relay.tex).

    python paper/laptop_w/trace_tables_lw.py [--check]

Lab job st1 ran on L alone, so its macros (results/trace-macros.tex, paper/trace_macros.py) belong
to the laptop set as October wrote them, and nothing of them is computed again. Its three table
bodies print the cost cells' comparison as C1 to C3; this file copies them into the laptop set's
tables with that column in words, from a fixed map, and changes nothing else. Each source must be
byte for byte the committed file at HEAD (git), and its sha256 is written in the copy's header. A
printed host, family or cell label in a copy stops the run.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import lw_common as C  # noqa: E402

SOURCES = ("counter-check.tex", "syscalls.tex", "ops-relay.tex")
FIRST_COLUMN = {"C1": "churn", "C2": "keep-alive", "C3": "fixed load"}


def committed(rel: str) -> bytes:
    return subprocess.run(["git", "-C", str(C.ROOT), "show", f"HEAD:{rel}"], capture_output=True, check=True).stdout


def reword(name: str, text: str) -> str:
    out = []
    for ln in text.splitlines():
        if ln.startswith("%"):
            continue
        if name == "counter-check.tex":
            first, sep, rest = ln.partition(" & ")
            ln = C.need(FIRST_COLUMN, first, "comparison") + sep + rest
        out.append(ln)
    return "\n".join(out) + "\n"


def build() -> dict[Path, str]:
    out = {}
    for name in SOURCES:
        src = C.RESULTS / "tables" / name
        rel = src.relative_to(C.ROOT).as_posix()
        data = src.read_bytes()
        if data != committed(rel):
            raise ValueError(f"{rel} differs from the committed file")
        head = (f"% Generated by paper/laptop_w/trace_tables_lw.py from {rel} (paper/trace_macros.py, lab job st1 on L),\n"
                f"% sha256 {C.sha256_file(src)}, with the comparison in words. Do not edit.\n")
        text = head + reword(name, data.decode("utf-8"))
        hits = C.printed_label_hits(text)
        if hits:
            raise ValueError(f"{name} prints internal labels: {sorted(set(hits))[:10]}")
        out[C.TABLES / name] = text
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare with the committed files, write nothing")
    a = ap.parse_args(argv)
    out = build()
    rc = C.write_all(out, a.check)
    if not a.check:
        print(f"trace tables (laptop set): {len(out)} files")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
